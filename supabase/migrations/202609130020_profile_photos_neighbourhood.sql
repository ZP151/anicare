create function public.list_my_community_photos(p_cursor jsonb default null,p_limit integer default 24)
returns table("postId" uuid,"mediaId" uuid,"position" integer,width integer,height integer,cursor jsonb)
language plpgsql stable security definer set search_path=pg_catalog as $$
declare actor uuid:=auth.uid(); after_created timestamptz; after_post uuid; after_position integer;
begin
 if actor is null then raise exception 'authentication_required' using errcode='42501'; end if;
 if p_limit is null or p_limit not between 1 and 48 then raise exception 'invalid_profile_photo_limit' using errcode='22023'; end if;
 if p_cursor is not null then
  begin
   if jsonb_typeof(p_cursor)<>'object' or (select count(*) from jsonb_object_keys(p_cursor))<>3
    or jsonb_typeof(p_cursor->'createdAt') is distinct from 'string'
    or jsonb_typeof(p_cursor->'postId') is distinct from 'string'
    or jsonb_typeof(p_cursor->'position') is distinct from 'number' then raise exception 'bad_cursor'; end if;
   after_created:=(p_cursor->>'createdAt')::timestamptz; after_post:=(p_cursor->>'postId')::uuid;
   after_position:=(p_cursor->>'position')::integer;
   if not isfinite(after_created) or after_position not between 0 and 5 then raise exception 'bad_cursor'; end if;
  exception when others then raise exception 'invalid_profile_photo_cursor' using errcode='22023'; end;
 end if;
 -- Seek on the returned tuple, not a live boundary row: deletion/holds between
 -- pages cannot invalidate the cursor. Every returned row still checks owner
 -- and current public availability. Private drafts/avatars/reports never join.
 return query
 select p.id,j.id,a.position::integer,j.display_width,j.display_height,
  jsonb_build_object('createdAt',p.created_at,'postId',p.id,'position',a.position)
 from public.community_posts p join private.community_post_media a on a.post_id=p.id
 join private.community_media_jobs j on j.id=a.media_id and j.owner_id=actor and j.status='attached'
 where p.author_id=actor and p.deleted_at is null and private.community_post_available(p.id,actor)
 and (p_cursor is null or (p.created_at,p.id)<(after_created,after_post)
  or ((p.created_at,p.id)=(after_created,after_post) and a.position>after_position))
 order by p.created_at desc,p.id desc,a.position asc limit p_limit;
end $$;
revoke all on function public.list_my_community_photos(jsonb,integer) from public,anon,authenticated,service_role;
grant execute on function public.list_my_community_photos(jsonb,integer) to authenticated;
commit;
